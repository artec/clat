const {test,expect}=require('@playwright/test');
const {hostInfo,openWorkbench,LIVE}=require('../helpers/workbench');
test('history search and inspector use committed facts without changing the composer or selection',async({page})=>{
  await openWorkbench(page,hostInfo('success'));
  await page.evaluate(()=>CLATI18n.setLanguage('en'));
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  await page.click('.project-group:has(#session-list) [data-action=new-project-session]');await expect(page.locator('#send')).toBeEnabled(LIVE);
  await page.fill('#prompt','历史检索 regression-needle <img src=x onerror=alert(1)>');await page.click('#send');
  await expect(page.locator('.msg.assistant').last()).toBeVisible(LIVE);await expect(page.locator('#cancel')).not.toBeVisible(LIVE);
  await page.evaluate(()=>refreshWorkbench());
  await expect.poll(()=>page.evaluate(()=>state.sessionId),LIVE).not.toBeNull();
  await page.fill('#prompt','未发送的中文草稿');
  const before=await page.evaluate(()=>state.sessionId);
  const mutations=[];page.on('request',r=>{if(/prompt.send|steer.send|session.switch|session.new|approval.respond/.test(r.url()))mutations.push(r.url());});
  await page.click('#nav-history');
  const dialog=page.locator('#history-dialog');await expect(dialog).toBeVisible();
  const results=dialog.locator('.history-results [data-reference]'),search=dialog.locator('.navigation-sidebar input[type=search]');
  await expect(results.first()).toBeVisible(LIVE);
  await search.fill('regression-needle');await search.press('Enter');
  const hit=results.filter({hasText:'regression-needle'}).first();
  await expect(hit).toBeVisible(LIVE);
  await expect(hit.locator('img')).toHaveCount(0);
  await hit.click();
  const inspector=dialog.locator('.trajectory-inspector');
  await expect(inspector.locator('.trajectory-detail-body')).toContainText('regression-needle',LIVE);
  await expect(inspector.locator('img')).toHaveCount(0);
  await inspector.getByRole('tab',{name:'Original',exact:true}).click();
  await inspector.getByRole('button',{name:'Copy original content',exact:true}).first().click();
  await expect.poll(()=>page.evaluate(()=>navigator.clipboard.readText())).toContain('regression-needle');
  await dialog.locator('[data-action=back-overview]').click();
  await expect(inspector).toHaveCount(0);
  await expect(search).toHaveValue('regression-needle');
  await page.click('#nav-workbench');
  await expect(page.locator('#prompt')).toHaveValue('未发送的中文草稿');
  expect(await page.evaluate(()=>state.sessionId)).toEqual(before);expect(mutations).toEqual([]);
});
